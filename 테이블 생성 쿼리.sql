CREATE TABLE ENROLL_INFO (
	ENROLL_NUM INT PRIMARY KEY
	, CLASS_NUM INT NOT NULL REFERENCES class_info (CLASS_NUM)
	, STU_NUM INT NOT NULL REFERENCES STU_INFO (STU_NUM)
	, STU_STATUS VARCHAR(30) NOT NULL DEFAULT '수강 등록'  #수강 등록,수강 중,수강 철회,수료,중도탈락, 80%수료, 80% 취업 
