	, CREATE_USER VARCHAR(50)
	, UPDATE_USER VARCHAR(50)
	, CREATE_DATE DATETIME DEFAULT SYSDATE()
	, UPDATE_DATE DATETIME
);


#수강 상담 데이터
CREATE TABLE CONSULT_INFO (
	CONSULT_NUM INT PRIMARY KEY AUTO_INCREMENT
	, STU_NUM INT NOT NULL REFERENCES STU_INFO (STU_NUM)
	, MANAGER_NUM INT NOT NULL REFERENCES staff_info (STAFF_NUM)	#담당자
	, CONSULT_CONTENT VARCHAR(2000)
	, CLASS_NUM INT NOT NULL REFERENCES class_info (CLASS_NUM)
	, CONSULT_STATUS VARCHAR(10) NOT NULL DEFAULT '미정' #미정 '등록 불확실' 가능성50% '등록 확정' 취소
	, CONSULT_TYPE VARCHAR(10) #실업자 재직자
	, SUPPORT_TYPE VARCHAR(10) #일반 국1, 국2
	, HRD_STATUS VARCHAR(15) #실업자 HRD선발, 재직자 HRD대기, 재직자 HRD선발
	, CONSULT_GRADE VARCHAR(5) #A, B, C
	, CUSTOM_ROWS JSON CHECK (JSON_VALID(CUSTOM_ROWS)),
	, ATTITUDE_SCORE INT #성향태도 점수
	, ATTENDANCE_SCORE INT # 출결예측 점수
	, MIND_SCORE INT # #수강의지 점수
	, JOB_SCORE INT # 취업역량 점수
	, TOTAL_SCORE INT #점수 합
	, CREATE_USER VARCHAR(50)
	, UPDATE_USER VARCHAR(50)
	, CREATE_DATE DATETIME DEFAULT SYSDATE()
	, UPDATE_DATE DATETIME
);


