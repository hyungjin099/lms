CREATE TABLE CLASS_OPER_INFO (
	CLASS_OPER_NUM INT PRIMARY KEY AUTO_INCREMENT
	, STAFF_NUM INT NOT NULL REFERENCES STAFF_INFO (STAFF_NUM)			#담당강사 번호
	, CLASS_ROOM INT NOT NULL REFERENCES CLASS_ROOM (CLASS_ROOM_NUM)	#강의실명
	, STUDY_DAY VARCHAR(30) NOT NULL												#수업요일
	, START_TIME TIME																	#수업 시작 시간
	, END_TIME TIME																	#수업 종료 시간
	, CLASS_NUM INT NOT NULL REFERENCES CLASS_INFO (CLASS_NUM)			#과정 번호
	, IS_USING VARCHAR(3) NOT NULL 												#적용 중 여부

);