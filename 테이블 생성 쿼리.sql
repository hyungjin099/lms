CREATE TABLE CLASS_INFO (
	CLASS_NUM INT PRIMARY KEY AUTO_INCREMENT
	, CLASS_NAME VARCHAR(100) NOT NULL									#과정명
	, JOB_NUM INT REFERENCES job_type (JOB_NUM)						#직종번호
	, CLASS_TYPE_NUM INT REFERENCES class_type (CLASS_TYPE_NUM)	#과정 유형 번호 
	, START_DATE DATE NOT NULL												#시작일
	, END_DATE DATE NOT NULL												#종료일
	, TOTAL_STUDY_DAY INT NOT NULL										#수업일수
	, TOTAL_STUDY_HOUR INT NOT NULL										#전체수업시간
	, CLASS_STATUS VARCHAR(50) NOT NULL DEFAULT '모집 중'			#과정상태 (모집 중, 진행 중, 종료)
	, CLASS_QUOTA INT NOT NULL DEFAULT 0								#모집 정원
	, CONFIRM_STU_CNT INT NOT NULL DEFAULT 0							#실시인원
	, JOIN_STU_CNT INT NOT NULL DEFAULT 0								#참여인원
	, DROP_STU_CNT INT  DEFAULT 0											#중탈인원
	, COMPLETE_STU_CNT INT  DEFAULT 0									#수료인원
	, EARLY_COMPLETE_CNT	INT DEFAULT 0									#80%수료인원
	, EARLY_EMPLOY_CNT INT DEFAULT 0										#80%취업인원
	, RECRUIT_RATE FLOAT NOT NULL	 DEFAULT 0.0						#모집률
	, CLASS_COMMENT VARCHAR(200)											#비고
	, CREATE_USER VARCHAR(50)
	, UPDATE_USER VARCHAR(50)
	, CREATE_DATE DATETIME DEFAULT SYSDATE()
	, UPDATE_DATE DATETIME
);


CREATE TABLE CLASS_OPER_INFO (
	CLASS_OPER_NUM INT PRIMARY KEY AUTO_INCREMENT
	, STAFF_NUM INT NOT NULL REFERENCES STAFF_INFO (STAFF_NUM)				#담당강사 번호
	, CLASS_ROOM_NUM INT NOT NULL REFERENCES CLASS_ROOM (CLASS_ROOM_NUM)	#강의실번호
	, STUDY_DAY VARCHAR(30) NOT NULL													#수업요일
	, STUDY_HOUR INT NOT NULL															#일일 수업 시간
	, START_TIME VARCHAR(10) NOT NULL												#수업 시작 시간
	, END_TIME VARCHAR(10) NOT NULL													#수업 종료 시간
	, CLASS_NUM INT NOT NULL REFERENCES CLASS_INFO (CLASS_NUM)				#과정 번호
	, IS_USING VARCHAR(3) NOT NULL DEFAULT 'Y'									#적용 중 여부
	, CREATE_USER VARCHAR(50)
	, UPDATE_USER VARCHAR(50)
	, CREATE_DATE DATETIME DEFAULT SYSDATE()
	, UPDATE_DATE DATETIME
);

